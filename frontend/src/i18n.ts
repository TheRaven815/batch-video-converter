export type TranslationParams = Record<string, string | number>;

const messages: Record<AppLanguage, Messages> = { en, tr };
const languageStorageKey = 'video-converter-language';

export function translate(
  language: AppLanguage,
  key: MessageKey,
  params: TranslationParams = {},
): string {
  return Object.entries(params).reduce(
    (message, [name, value]) => message.replaceAll(`{{${name}}}`, String(value)),
    messages[language][key],
  );
}

export function loadLanguage(): AppLanguage {
  const stored = localStorage.getItem(languageStorageKey);
  if (stored === 'en' || stored === 'tr') return stored;
  return navigator.language.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

type I18nContextValue = {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  toggleLanguage: () => void;
  t: (key: MessageKey, params?: TranslationParams) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(loadLanguage);

  const setLanguage = useCallback((next: AppLanguage) => {
    localStorage.setItem(languageStorageKey, next);
    document.documentElement.lang = next;
    setLanguageState(next);
  }, []);

  const toggleLanguage = useCallback(
    () => setLanguage(language === 'en' ? 'tr' : 'en'),
    [language, setLanguage],
  );
  const t = useCallback(
    (key: MessageKey, params?: TranslationParams) => translate(language, key, params),
    [language],
  );
  const value = useMemo(
    () => ({ language, setLanguage, toggleLanguage, t }),
    [language, setLanguage, t, toggleLanguage],
  );

  useEffect(() => {
    document.documentElement.lang = language;
    document.title = t('app.name');
  }, [language, t]);

  return createElement(I18nContext.Provider, { value }, children);
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}
